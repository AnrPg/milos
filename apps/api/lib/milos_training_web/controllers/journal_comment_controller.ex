defmodule MilosTrainingWeb.JournalCommentController do
  @moduledoc """
  Σχόλια (ADR-140 §1): the member's comments on their own executions,
  training-log entries and PRs. Saves are idempotent upserts by the
  client-generated id, so the offline outbox can replay them.
  """

  use MilosTrainingWeb, :controller
  use OpenApiSpex.ControllerSpecs

  alias MilosTraining.Application.JournalComments
  alias MilosTrainingWeb.Schemas.JournalComments, as: Schemas
  alias OpenApiSpex.{MediaType, Parameter, RequestBody, Schema}

  action_fallback MilosTrainingWeb.FallbackController

  tags(["Journal"])
  security([%{"bearerAuth" => []}])

  plug(
    OpenApiSpex.Plug.CastAndValidate,
    [json_render_error_v2: true] when action in [:save, :batch]
  )

  @id_param %Parameter{
    name: :id,
    in: :path,
    required: true,
    description: "Comment id (generated by the client)",
    schema: %Schema{type: :string, format: :uuid}
  }

  operation(:save,
    summary: "Write or edit a comment on one of your entries",
    parameters: [@id_param],
    request_body: %RequestBody{
      required: true,
      content: %{"application/json" => %MediaType{schema: Schemas.save_request()}}
    },
    responses: [
      ok: {"Comment", "application/json", Schemas.comment_response()},
      not_found: {"Entry or comment not found", "application/json", %Schema{type: :object}},
      conflict: {"Id belongs to another entry", "application/json", %Schema{type: :object}}
    ]
  )

  def save(conn, %{id: id}) do
    with {:ok, comment} <-
           JournalComments.save(conn.assigns.user_context, id, body_params(conn)) do
      json(conn, %{comment: comment})
    end
  end

  operation(:batch,
    summary: "Write or edit several comments at once (all or none)",
    request_body: %RequestBody{
      required: true,
      content: %{"application/json" => %MediaType{schema: Schemas.batch_request()}}
    },
    responses: [ok: {"Comments", "application/json", Schemas.comments_response()}]
  )

  def batch(conn, _params) do
    with {:ok, comments} <-
           JournalComments.save_many(conn.assigns.user_context, body_params(conn)["comments"]) do
      json(conn, %{comments: comments})
    end
  end

  operation(:delete,
    summary: "Delete one of your comments",
    parameters: [@id_param],
    responses: [no_content: "Deleted"]
  )

  def delete(conn, %{"id" => id}) do
    with :ok <- JournalComments.delete(conn.assigns.user_context, id) do
      send_resp(conn, :no_content, "")
    end
  end

  # CastAndValidate atomizes known keys; the application works on the raw
  # JSON body so nested change patches keep their string keys.
  defp body_params(conn), do: conn.body_params |> Jason.encode!() |> Jason.decode!()
end
